import type { CardData } from "@/lib/types";

interface CachedPool {
pool: CardData[];
best: CardData;
average: CardData;
worst: CardData;
}

const poolCache = new Map<number, CachedPool>();

/**

- Build the pool of cards that can be generated by a source card.
*/
export function buildPool(source: CardData, registry: Map<number, CardData>): CardData[] {
const text = (source.text || "").toLowerCase();
const tags = source.referencedTags ?? [];

let filterType: string | null = null;
let filterRace: string | null = null;
let filterClass: string | null = null;
let filterCostMax: number | null = null;

if (/minion|существо/i.test(text)) filterType = "MINION";
if (/spell|заклинание/i.test(text)) filterType = "SPELL";
if (/weapon|оружие/i.test(text)) filterType = "WEAPON";

const raceTags = ["DRAGON", "BEAST", "MURLOC", "DEMON", "ELEMENTAL", "MECH", "PIRATE", "TOTEM", "UNDEAD"];
for (const t of tags) if (raceTags.includes(t)) filterRace = t;

const classes = ["PALADIN", "MAGE", "WARRIOR", "ROGUE", "PRIEST", "HUNTER", "WARLOCK", "DRUID", "SHAMAN", "DEMON_HUNTER", "DEATH_KNIGHT"];
for (const cl of classes) if (text.includes(cl.toLowerCase())) filterClass = cl;

const costMatch = text.match(/cost\s*\s*or\s*less|стоимостью\s*\s*или\s*меньше/i);
if (costMatch) filterCostMax = parseInt(costMatch[1] ?? costMatch[2]);

const pool: CardData[] = [];
for (const c of registry.values()) {
if (c.type === "HERO" || c.type === "HERO_POWER" || c.type === "ENCHANTMENT") continue;
if (filterType && c.type !== filterType) continue;
if (filterClass && c.cardClass !== filterClass && c.cardClass !== "NEUTRAL") continue;
if (filterRace && c.race !== filterRace) continue;
if (filterCostMax !== null && (c.cost ?? 0) > filterCostMax) continue;
pool.push(c);
}

return pool;
}

/**

- Get (and cache) the Discover pool for a source card.
- Cache is keyed by dbfId so the same pool is reused across games.
*/
export function getPool(source: CardData, registry: Map<number, CardData>): CachedPool | null {
const cached = poolCache.get(source.dbfId);
if (cached) return cached;

const pool = buildPool(source, registry);
if (pool.length === 0) return null;

const sorted = [...pool].sort((a, b) => (a.cost ?? 0) - (b.cost ?? 0));
const result: CachedPool = {
pool,
best: sorted[sorted.length - 1],
average: sorted[Math.floor(sorted.length / 2)],
worst: sorted[0]
};
poolCache.set(source.dbfId, result);
return result;
}

/**

- Pick from pool using the user's rule: 1/3 best, 1/3 average, 1/3 worst.
*/
export function pickCurated(pool: CardData[], rng: () => number): CardData | null {
if (pool.length === 0) return null;
const sorted = [...pool].sort((a, b) => (a.cost ?? 0) - (b.cost ?? 0));
const roll = rng();
if (roll < 1 / 3) return sorted[sorted.length - 1];
if (roll < 2 / 3) return sorted[Math.floor(sorted.length / 2)];
return sorted[0];
}

/**

- Resolve Discover: uses cached pool + best/average/worst pick.
*/
export function resolveDiscover(
source: CardData,
registry: Map<number, CardData>,
rng: () => number
): CardData | null {
const cached = getPool(source, registry);
if (!cached) return null;
const roll = rng();
if (roll < 1 / 3) return cached.best;
if (roll < 2 / 3) return cached.average;
return cached.worst;
}

/**

- Check if a card generates random cards (Discover or "add a random").
*/
export function hasRandomGeneration(card: CardData): boolean {
const text = (card.text || "").toLowerCase();
return (
card.mechanics.includes("DISCOVER") ||
/discover|раскоп|random|случайн/i.test(text)
);
}

/**

- Reset pool cache (for testing).
*/
export function clearPoolCache(): void {
poolCache.clear();
}